"""Geometry descriptors shared by the band-path, sparsity and preset layers.

Dependency-free (numpy is used for speed when present). Element data come
from ``sparse_dft/data/elements.json`` (generated by tools/build_element_table.py,
sources recorded there).

* ``axis_vacuum``: the largest empty slab along each lattice axis, measured
  along the plane normal (interplanar spacing), not along the axis length.
* ``bonded_dimensionality``: per bonded component, the rank of the lattice
  translations its bond network closes over (rank-determination method of
  Larsen et al., Phys. Rev. Mater. 3, 034003 (2019)). 0 = molecule,
  1 = chain, 2 = layer, 3 = framework. Bonds use covalent radii times
  ``bond_scale``.
"""
from __future__ import annotations

import functools
import json
import math
from dataclasses import dataclass, field
from pathlib import Path

from .errors import InputError
from .structure import Structure, _inverse, _norm

ELEMENTS_PATH = Path(__file__).with_name('data') / 'elements.json'
# Gap below which an interatomic slab counts as bonding geometry, not vacuum
# (same convention as sparse_dft.sparsity.vacuum_fraction).
VACUUM_GAP_ANGSTROM = 5.0
BOND_SCALE = 1.20
# Used for elements whose covalent radius is unknown in the table.
FALLBACK_RADIUS_ANGSTROM = 1.5


@functools.lru_cache(maxsize=1)
def element_table() -> dict[str, dict]:
    data = json.loads(ELEMENTS_PATH.read_text(encoding='utf-8'))
    return {row['symbol']: row for row in data['elements']}


def element(symbol: str) -> dict:
    row = element_table().get(str(symbol).strip().capitalize())
    if row is None:
        raise InputError('unknown chemical element', details={'symbol': symbol})
    return row


def interplanar_spacings(lattice) -> tuple[float, float, float]:
    """d_i = 1/|b_i| with b the reciprocal rows of A^-T (no 2 pi)."""
    inv = _inverse(lattice)
    return tuple(1.0 / _norm(row) for row in inv)


@dataclass
class AxisVacuum:
    gap_angstrom: tuple[float, float, float]
    gap_fraction: tuple[float, float, float]
    spacing_angstrom: tuple[float, float, float]
    vacuum_axes: tuple[bool, bool, bool]

    def as_dict(self) -> dict:
        return {'gap_angstrom': list(self.gap_angstrom), 'gap_fraction': list(self.gap_fraction),
                'spacing_angstrom': list(self.spacing_angstrom), 'vacuum_axes': list(self.vacuum_axes)}


def axis_vacuum(structure: Structure, threshold_angstrom: float = VACUUM_GAP_ANGSTROM) -> AxisVacuum:
    if structure.lattice is None:
        inf = (math.inf,) * 3
        return AxisVacuum(inf, (1.0, 1.0, 1.0), inf, (True, True, True))
    s = structure.normalized()
    spacing = interplanar_spacings(s.lattice)
    gaps, fractions = [], []
    for axis in range(3):
        coords = sorted(p[axis] % 1.0 for p in s.positions)
        steps = [b - a for a, b in zip(coords, coords[1:])] + [coords[0] + 1.0 - coords[-1]]
        frac = max(steps)
        fractions.append(frac)
        gaps.append(frac * spacing[axis])
    return AxisVacuum(tuple(gaps), tuple(fractions), spacing,
                      tuple(g > threshold_angstrom for g in gaps))


def _rank(vectors) -> int:
    rows = [list(map(float, v)) for v in vectors]
    rank = 0
    for col in range(3):
        pivot = next((r for r in range(rank, len(rows)) if abs(rows[r][col]) > 1e-9), None)
        if pivot is None:
            continue
        rows[rank], rows[pivot] = rows[pivot], rows[rank]
        for r in range(len(rows)):
            if r != rank and abs(rows[r][col]) > 1e-9:
                factor = rows[r][col] / rows[rank][col]
                rows[r] = [a - factor * b for a, b in zip(rows[r], rows[rank])]
        rank += 1
    return rank


@dataclass
class Connectivity:
    dimensionality: int
    components: list[dict] = field(default_factory=list)
    bond_scale: float = BOND_SCALE
    bonds: int = 0

    def as_dict(self) -> dict:
        return {'dimensionality': self.dimensionality, 'components': self.components,
                'bond_scale': self.bond_scale, 'bonds': self.bonds}


def _bonds(structure: Structure, bond_scale: float):
    """Yield (i, j, image) for every bonded pair, images as integer triples."""
    s = structure.normalized()
    radii = []
    for symbol in s.species:
        r = element(symbol).get('covalent_radius_angstrom')
        radii.append(float(r) if r else FALLBACK_RADIUS_ANGSTROM)
    cutoff = bond_scale * 2.0 * max(radii)
    inv = _inverse(s.lattice)
    reach = [math.ceil(cutoff * _norm(row)) + 1 for row in inv]
    images = [(a, b, c) for a in range(-reach[0], reach[0] + 1) for b in range(-reach[1], reach[1] + 1)
              for c in range(-reach[2], reach[2] + 1)]
    lat = s.lattice
    frac = s.positions
    n = len(frac)
    try:
        import numpy as np
    except ImportError:  # pragma: no cover - numpy is present in GUI installs
        np = None
    if np is not None:
        L = np.asarray(lat, dtype=float)
        F = np.asarray(frac, dtype=float)
        R = np.asarray(radii)
        I = np.asarray(images, dtype=float)
        shift = I @ L
        for i in range(n):
            d = (F - F[i]) @ L                      # (n, 3)
            vec = d[None, :, :] + shift[:, None, :]  # (images, n, 3)
            dist = np.sqrt((vec * vec).sum(-1))
            limit = bond_scale * (R[i] + R)[None, :]
            hit = (dist < limit) & (dist > 1e-6)
            for m, j in zip(*np.nonzero(hit)):
                if j >= i:
                    yield i, int(j), images[int(m)]
        return
    for i in range(n):
        for j in range(i, n):
            limit = bond_scale * (radii[i] + radii[j])
            for img in images:
                f = [frac[j][k] - frac[i][k] + img[k] for k in range(3)]
                v = [sum(f[k] * lat[k][c] for k in range(3)) for c in range(3)]
                d = _norm(v)
                if 1e-6 < d < limit:
                    yield i, j, img


def bonded_dimensionality(structure: Structure, bond_scale: float = BOND_SCALE,
                          max_atoms: int = 2000) -> Connectivity:
    if structure.lattice is None:
        return Connectivity(0, [{'atoms': list(range(structure.natoms)), 'dimensionality': 0}], bond_scale)
    if structure.natoms > max_atoms:
        raise InputError('structure too large for connectivity analysis', details={'natoms': structure.natoms,
                         'max_atoms': max_atoms})
    n = structure.natoms
    adjacency: list[list[tuple[int, tuple[int, int, int]]]] = [[] for _ in range(n)]
    count = 0
    for i, j, img in _bonds(structure, bond_scale):
        adjacency[i].append((j, img))
        if i != j or any(img):
            adjacency[j].append((i, tuple(-x for x in img)))
        count += 1
    offset: list[tuple[int, int, int] | None] = [None] * n
    components = []
    for start in range(n):
        if offset[start] is not None:
            continue
        offset[start] = (0, 0, 0)
        stack, members, cycles = [start], [], []
        while stack:
            i = stack.pop()
            members.append(i)
            for j, img in adjacency[i]:
                target = tuple(offset[i][k] + img[k] for k in range(3))
                if offset[j] is None:
                    offset[j] = target
                    stack.append(j)
                else:
                    loop = tuple(target[k] - offset[j][k] for k in range(3))
                    if any(loop):
                        cycles.append(loop)
        components.append({'atoms': sorted(members), 'dimensionality': _rank(cycles) if cycles else 0})
    dim = max(c['dimensionality'] for c in components)
    return Connectivity(dim, components, bond_scale, count)
